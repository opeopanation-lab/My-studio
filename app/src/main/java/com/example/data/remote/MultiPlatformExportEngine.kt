    private fun cleanCodeBlock(text: String): String {
        var clean = text.trim()
        if (clean.startsWith("```")) {
            val firstLineEnd = clean.indexOf("\n")
            if (firstLineEnd != -1) {
                clean = clean.substring(firstLineEnd + 1)
            }
        }
        if (clean.endsWith("```")) {
            clean = clean.substring(0, clean.length - 3).trimEnd()
        }
        return clean
    }
