    suspend fun convertCode(
        sourceCode: String,
        sourceLanguage: Language,
        targetLanguage: Language,
        sourceFramework: String,
        targetFramework: String
    ): CodeConversionResult {
        // Attempt Gemini AI conversion first
        val prompt = """
You are Nation Wide Studio's expert multi-language code compiler and framework converter.
Translate the following ${sourceLanguage.displayName} (${sourceFramework}) code into idiomatic, production-ready, type-safe ${targetLanguage.displayName} (${targetFramework}) code.

Source Code:
```${sourceLanguage.extension}
$sourceCode
```

Instructions:
1. Maintain exact semantic parity, async behaviors, error handling, and data structures.
2. Adapt framework idioms seamlessly (e.g. decorators, endpoints, types, state management).
3. Provide only the raw target code inside standard markdown codeblocks ```${targetLanguage.extension} ... ``` without unnecessary introductory conversational filler.
4. Follow modern ${targetLanguage.displayName} best practices.
""".trimIndent()

        val geminiResult = geminiService.callGemini(
            prompt = prompt,
            systemInstruction = "You are Nation Wide Studio's high-accuracy multi-language code migration engine."
        )

        var convertedCode = ""
        var translationNotes = "Converted via Nation Wide Studio AI Code Translation Engine."

        if (geminiResult.isSuccess && geminiResult.getOrNull()?.isNotBlank() == true) {
            val raw = geminiResult.getOrNull()!!
            convertedCode = extractCodeBlock(raw, targetLanguage.extension)
            translationNotes = "High-accuracy AI neural translation with ${targetFramework} idioms applied."
        } else {
            // Intelligent fallback transpilation engine
            convertedCode = fallbackTranspile(sourceCode, sourceLanguage, targetLanguage, sourceFramework, targetFramework)
            translationNotes = "Rule-based high-accuracy fallback transpiler applied. Framework mapping: ${sourceFramework} -> ${targetFramework}."
        }

        // Framework mappings info
        val mappings = generateFrameworkMappings(sourceLanguage, targetLanguage, sourceFramework, targetFramework)
        val diagnostics = checkSyntax(convertedCode, targetLanguage)
        val suggestions = generateSuggestions(convertedCode, targetLanguage)

        return CodeConversionResult(
            sourceCode = sourceCode,
            targetCode = convertedCode,
            sourceLanguage = sourceLanguage,
            targetLanguage = targetLanguage,
            sourceFramework = sourceFramework,
            targetFramework = targetFramework,
            translationNotes = translationNotes,
            frameworkMappings = mappings,
            diagnostics = diagnostics,
            suggestions = suggestions
        )
    }

