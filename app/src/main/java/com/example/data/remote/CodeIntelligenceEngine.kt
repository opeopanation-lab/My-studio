    private fun extractSignatures(code: String, language: Language): List<String> {
        val signatures = mutableListOf<String>()
        val lines = code.lines()
        for (line in lines) {
            val t = line.trim()
            if (t.startsWith("def ") || t.startsWith("class ") || t.startsWith("export function") || t.startsWith("public ") || t.startsWith("fun ") || t.startsWith("fn ") || t.startsWith("struct ")) {
                signatures.add(t.take(60))
            }
        }
        if (signatures.isEmpty()) {
            signatures.add("TaskManager.processTask(task: UserTask)")
        }
        return signatures
    }

    private fun extractCodeBlock(markdown: String, expectedExt: String): String {
        val lines = markdown.lines()
        val codeLines = mutableListOf<String>()
        var insideBlock = false

        for (line in lines) {
            if (line.trim().startsWith("```")) {
                if (insideBlock) {
                    break
                } else {
                    insideBlock = true
                    continue
                }
            }
            if (insideBlock) {
                codeLines.add(line)
            }
        }

        if (codeLines.isNotEmpty()) {
            return codeLines.joinToString("\n").trim()
        }

        return markdown.trim()
    }

