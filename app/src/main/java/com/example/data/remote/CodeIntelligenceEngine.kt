    fun checkSyntax(code: String, language: Language): List<SyntaxDiagnostic> {
        val diagnostics = mutableListOf<SyntaxDiagnostic>()
        val lines = code.lines()

        // Brackets / parentheses balance check
        var openBraces = 0
        var openParens = 0
        var openBrackets = 0

        lines.forEachIndexed { index, line ->
            val lineNum = index + 1
            val trimmed = line.trim()

            // Check for common syntax pitfalls per language
            when (language) {
                Language.PYTHON -> {
                    if (trimmed.startsWith("def ") || trimmed.startsWith("class ") || trimmed.startsWith("if ") || trimmed.startsWith("for ") || trimmed.startsWith("while ") || trimmed.startsWith("async def ")) {
                        if (!trimmed.endsWith(":") && !trimmed.contains(": #")) {
                            diagnostics.add(
                                SyntaxDiagnostic(
                                    line = lineNum,
                                    column = trimmed.length,
                                    severity = DiagnosticSeverity.ERROR,
                                    message = "SyntaxError: Expected ':' at end of statement",
                                    ruleId = "py-missing-colon",
                                    quickFixSuggestion = "$line:"
                                )
                            )
                        }
                    }
                    if (line.contains(";") && !line.contains("\"") && !line.contains("'")) {
                        diagnostics.add(
                            SyntaxDiagnostic(
                                line = lineNum,
                                column = line.indexOf(';'),
                                severity = DiagnosticSeverity.INFO,
                                message = "PEP8: Trailing semicolon is unidiomatic in Python",
                                ruleId = "py-unnecessary-semicolon",
                                quickFixSuggestion = line.replace(";", "")
                            )
                        )
                    }
                }
                Language.JAVASCRIPT, Language.TYPESCRIPT -> {
                    if (trimmed.startsWith("const ") && !trimmed.contains("=") && !trimmed.endsWith("{")) {
                        diagnostics.add(
                            SyntaxDiagnostic(
                                line = lineNum,
                                column = 1,
                                severity = DiagnosticSeverity.ERROR,
                                message = "SyntaxError: Missing initializer in const declaration",
                                ruleId = "js-const-init"
                            )
                        )
                    }
                }
                Language.RUST -> {
                    if (trimmed.startsWith("let ") && !trimmed.endsWith(";") && !trimmed.endsWith("{") && !trimmed.endsWith(",")) {
                        diagnostics.add(
                            SyntaxDiagnostic(
                                line = lineNum,
                                column = line.length,
                                severity = DiagnosticSeverity.WARNING,
                                message = "Expected ';' at the end of statement",
                                ruleId = "rs-missing-semi",
                                quickFixSuggestion = "$line;"
                            )
                        )
                    }
                }
                Language.KOTLIN, Language.JAVA -> {
                    if (trimmed.startsWith("var ") && trimmed.endsWith("=")) {
                        diagnostics.add(
                            SyntaxDiagnostic(
                                line = lineNum,
                                column = line.length,
                                severity = DiagnosticSeverity.ERROR,
                                message = "Expression expected after assignment",
                                ruleId = "kt-missing-assignment-expr"
                            )
                        )
                    }
                }
                else -> {}
            }

            // Count delimiters
            openBraces += line.count { it == '{' } - line.count { it == '}' }
            openParens += line.count { it == '(' } - line.count { it == ')' }
            openBrackets += line.count { it == '[' } - line.count { it == ']' }
        }

        if (openBraces != 0) {
            diagnostics.add(
                SyntaxDiagnostic(
                    line = lines.size,
                    column = 1,
                    severity = DiagnosticSeverity.ERROR,
                    message = "Unbalanced curly braces: ${if (openBraces > 0) "$openBraces unclosed" else "${-openBraces} extra closed"}",
                    ruleId = "syntax-unbalanced-braces"
                )
            )
        }
        if (openParens != 0) {
            diagnostics.add(
                SyntaxDiagnostic(
                    line = lines.size,
                    column = 1,
                    severity = DiagnosticSeverity.ERROR,
                    message = "Unbalanced parentheses: ${if (openParens > 0) "$openParens unclosed" else "${-openParens} extra closed"}",
                    ruleId = "syntax-unbalanced-parens"
                )
            )
        }

        if (diagnostics.isEmpty()) {
            diagnostics.add(
                SyntaxDiagnostic(
                    line = 1,
                    column = 1,
                    severity = DiagnosticSeverity.INFO,
                    message = "Syntax check passed: 0 errors, 0 warnings. Code is valid ${language.displayName}.",
                    ruleId = "syntax-ok"
                )
            )
        }

        return diagnostics
    }

