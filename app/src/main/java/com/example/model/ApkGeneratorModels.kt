package com.example.model

enum class ApkAppType(val displayName: String, val description: String) {
    NATIVE_COMPOSE(
        displayName = "Native Jetpack Compose UI",
        description = "Compiles code logic into modern reactive Material 3 Android UI with ViewModels and Coroutines"
    ),
    HYBRID_WEBVIEW(
        displayName = "Hybrid WebView Container",
        description = "Packages HTML/JavaScript/Web code into a hardware-accelerated Android WebView with native JS Bridge"
    ),
    BACKGROUND_WORKER(
        displayName = "Android Service & WorkManager",
        description = "Runs code logic in a reliable background service and periodic WorkManager tasks"
    ),
    REST_API_CLIENT(
        displayName = "Mobile API Client & Repository",
        description = "Generates Retrofit/Ktor networking client, data models, and caching layers for mobile consumption"
    )
}

enum class ApkBuildStatus {
    IDLE,
    PARSING_SOURCE,
    GENERATING_COMPOSE_UI,
    CONFIGURING_MANIFEST_GRADLE,
    COMPILING_BYTECODE,
    DEXING_R8,
    ALIGNING_ZIP,
    SIGNING_APK,
    SUCCESS,
    FAILED
}

data class ApkConfig(
    val appName: String = "NationWide App",
    val packageName: String = "com.nationwide.app",
    val versionName: String = "1.0.0",
    val versionCode: Int = 1,
    val minSdk: Int = 24,
    val targetSdk: Int = 34,
    val appType: ApkAppType = ApkAppType.NATIVE_COMPOSE,
    val primaryColorHex: String = "#00F0FF",
    val secondaryColorHex: String = "#0284C7",
    val permissions: List<String> = listOf(
        "android.permission.INTERNET",
        "android.permission.ACCESS_NETWORK_STATE",
        "android.permission.POST_NOTIFICATIONS",
        "android.permission.VIBRATE"
    ),
    val enableDynamicColor: Boolean = true,
    val isHardwareAccelerated: Boolean = true,
    val appIconSymbol: String = "code", // code, rocket, phone, bolt, terminal
    val author: String = "NationWide Studio",
    val description: String = "Production Android application generated by NationWide Studio"
)

data class ApkBuildLogEntry(
    val timestamp: Long = System.currentTimeMillis(),
    val step: String,
    val message: String,
    val isError: Boolean = false
)

