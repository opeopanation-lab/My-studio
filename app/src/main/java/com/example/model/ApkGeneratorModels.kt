    val config: ApkConfig,
    val mainActivityCode: String,
    val composeUiCode: String,
    val viewModelCode: String,
    val manifestXml: String,
    val buildGradleKts: String,
    val settingsGradleKts: String,
    val stringsXml: String,
    val colorsXml: String,
    val themesXml: String,
    val proguardRules: String,
    val allFiles: Map<String, String>,
    val apkSizeFormatted: String = "14.6 MB",
    val apkFileName: String = "NationWideApp-1.0.0-debug.apk",
    val sha256Digest: String = "d4e28f7a6c9b3105e1928374a5f6e7d8c9b0a1f2e3d4c5b6a7b8c9d0e1f2a3b4",
    val timestamp: Long = System.currentTimeMillis()
)
